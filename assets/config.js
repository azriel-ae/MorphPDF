/* =====================================================================
   MorphPDF - App Configuration
   Tailwind theme + PDF.js worker setup.
   Must load AFTER the Tailwind CDN script and pdf.js library script.

   COLOR SYSTEM NOTE
   -----------------
   index.html AND the HTML strings generated by script.js / pdf-tools.js /
   excel-tools.js share the same Tailwind utility classes. Rather than
   touching functional code, the palettes are remapped here so every
   screen - including dynamically rendered result cards and file lists -
   follows the MorphPDF design system:

     warm cream base       (gray, zinc  -> warm neutrals)
     amber solid           (red-600/700 -> primary CTA buttons, active icons)
     apricot accent        (red-50..500 -> chips, icon tints, borders)
     warm amber success    (green       -> success states)
     deep warm brown       (amber       -> warning states)

   No red, blue, purple or green hues are rendered anywhere.
   ===================================================================== */

